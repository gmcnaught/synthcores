// NEC/Casio uPD933 "Phase Distortion" sound chip, bit-exact to MAME's behavioural model
// (src/devices/sound/upd933.cpp, Devin Acker; standalone copy in cores/cz101/ref/upd933_ref.cpp).
//
// Time base: 10 MHz ticks (the CZ-101 CPU crystal); one 40 kHz sample = 250 ticks.
// now_tick is the master's logical time: a promise that no later request has req_order < now_tick
// (for the CZ-101: the CPU's current instruction start; a free-running 10 MHz counter also works
// if every request is presented before the counter passes its req_order). now_tick must not
// decrease. Sample k is computed once now_tick >= t0 + k*250, t0 = now_tick during rst (0 on the
// board; 8 voices one after another in MAME's voice_map order, about 30 clk per voice); the IRQ
// timer fires once now_tick >= its deadline.
// Ticks are 40 bits and wrap (after 2^40 ticks, 30.5 h at 10 MHz): every tick comparison is
// modular (t_ge), valid while the two ticks are less than 2^39 apart (15 h). Ticks compared here
// are at most a few samples apart, except an internal timer deadline (at most 250 * 2^30 ticks
// ahead, 7.5 h).
// `settled` is high when nothing is due at now_tick (sample, timer) and no request is in progress:
// sample irq only when settled.
//
// Bus: one request at a time. Hold req_valid (with op/data/tick/order) until req_ack (one clk,
// with rd_data for a read). req_tick is the access time in ticks as MAME's machine().time() would
// give it. The access is applied after the samples MAME has generated by req_tick:
// floor(req_tick/250)+1 of them; a request may wait for its sample to be computed (now_tick must
// reach its boundary), and one that arrives after the following sample was computed sets `late`.
// req_order: an armed IRQ timer with deadline <= req_order fires before the access (req_order =
// req_tick unless modelling MAME's instruction overshoot; req_order <= req_tick).
// Request ticks must not decrease. req_tick = 0 is not supported (MAME: no stream update at t=0).
//   op 0 write byte, 1 read, 2 /CS level (data[0]), 3 /ID level (data[0]), 4 device reset,
//   5 stream sync (no effect).
//
// IRQ: irq = /CS & /ID & pending, as MAME. irq_evt pulses on every change with the tick MAME
// would log it at (timer deadline or request tick). The timer deadline is tick + 250 * new_time.
//
// External timer (ext_timer = 1, for exact placement at CPU instruction boundaries): the internal
// deadline compare is off. The chip reports every adjust() of MAME's IRQ timer and the board fires it:
//   timer_arm + timer_n (one clk): update_pending_irq() armed the timer for timer_n samples
//     (new_time; MAME's expiry is T_arm + timer_n * 112 chip clocks, T_arm = the arming access).
//     Only a /CS rising edge (op 2, data[0] 0 -> 1) calls update_pending_irq(); the pulse is in the
//     clock of that request's req_ack. timer_n = 0 when an envelope IRQ flag is already set.
//   timer_cancel (one clk): adjust(attotime::never). From the same /CS rising edge when no envelope
//     is active (pulse with its req_ack), and from a device reset (op 4, pulse while it is serviced,
//     before its req_ack). Arming again replaces the previous expiry, as adjust() does.
//   timer_fire (input, one clk): timer_tick(): pending = 1 and the IRQ update, no stream update.
//     irq_evt_tick takes timer_fire_tick. Pulse it only while req_valid is low (between requests);
//     the board disarms its own copy when it fires (MAME's timer is one-shot).
// timer_arm/timer_n/timer_cancel are also driven when ext_timer = 0.
//
// Noise: MAME's machine().rand() (LCG 1664525/1013904223) from RAND_SEED, advanced only by this
// chip.
//
// Storage: envelope state in three 8-entry RAMs (DCA, DCW, DCO), 72 bits each; voice state in
// registers; four ROMs (cosine 2048x12, pitch 128x30, fine pitch 512x8, volume 512x14) loaded
// from the .hex files written by cores/cz101/ref/upd933_tables.cpp. One shared multiplier.

module upd933 #(
	parameter logic [31:0] RAND_SEED = 32'h9d14abd7,
	parameter TABLE_DIR = "./"             // prefix for upd933_*.hex (non-empty: concatenated as bits)
) (
	input  logic               clk,
	input  logic               rst,
	input  logic [39:0]        now_tick,
	output logic               settled,

	input  logic               req_valid,
	input  logic [2:0]         req_op,
	input  logic [7:0]         req_data,
	input  logic [39:0]        req_tick,
	input  logic [39:0]        req_order,
	output logic               req_ack,
	output logic [7:0]         rd_data,

	input  logic               ext_timer,
	output logic               timer_arm,
	output logic [31:0]        timer_n,
	output logic               timer_cancel,
	input  logic               timer_fire,
	input  logic [39:0]        timer_fire_tick,

	output logic               irq,
	output logic               irq_evt,
	output logic [39:0]        irq_evt_tick,

	output logic               sample_valid,
	output logic signed [18:0] sample_sum,   // s32 sum of the 8 voices (fits 19 bits)
	output logic signed [15:0] sample_out,   // clamped like put_int_clamp

	output logic               late,         // sticky: a request came after its sample boundary
	output logic               busy
);

	localparam logic [2:0] OP_WR = 3'd0, OP_RD = 3'd1, OP_CS = 3'd2, OP_ID = 3'd3, OP_RESET = 3'd4;
	localparam logic [39:0] TPS = 40'd250;
	localparam logic [31:0] LCG_A = 32'd1664525, LCG_C = 32'd1013904223;

	typedef enum logic [5:0] {
		S_IDLE,
		E_RD, E_WAIT, E_LATCH, E_PH, E_DIV, E_RES, E_COS, E_WIN, E_VOL, E_RING, E_RING2, E_MUTE,
		E_RAND1, E_RAND2, E_RAND3, E_CHK, E_WB,
		P0, P1, P2, P3,
		B_ENV_WAIT, B_ENV_LATCH, B_ENV_DIV, B_ENV_WR, B_PITCH_WAIT, B_PITCH_LATCH,
		B_SCAN_RD, B_SCAN_WAIT, B_SCAN_USE, B_SCAN_DONE, B_RST
	} state_t;
	state_t state;

	// ------------------------------------------------------------------ voice registers
	logic [2:0]  v_wave0 [0:7];
	logic [2:0]  v_wave1 [0:7];
	logic [2:0]  v_window [0:7];
	logic        v_ring [0:7];
	logic [1:0]  v_pmod [0:7];
	logic        v_mute [0:7];
	logic [15:0] v_pitch [0:7];
	logic [15:0] v_pm [0:7];
	logic [31:0] v_pos [0:7];
	logic [31:0] v_step [0:7];
	logic [10:0] v_dcwlim [0:7];

	// ------------------------------------------------------------------ envelope RAMs
	// entry: [71] direction, [70:64] rate code, [63:57] level bits, [56:30] current, [29:0] countdown
	// countdown = MAME's calc_timeout() value, kept up to date (minus one per sample) so that a
	// /CS rising edge needs no division.
	logic        env_we [0:2];
	logic [2:0]  env_wa, env_ra;
	logic [71:0] env_wd [0:2];
	logic [71:0] env_q  [0:2];
	logic [23:0] irqf, susf;   // index kind*8 + voice; kind 0 DCA, 1 DCW, 2 DCO

	genvar gk;
	generate
		for (gk = 0; gk < 3; gk = gk + 1) begin : g_env
			upd933_ram #(.AW(3), .DW(72)) ram (
				.clk(clk), .we(env_we[gk]), .wa(env_wa), .wd(env_wd[gk]), .ra(env_ra), .q(env_q[gk]));
		end
	endgenerate

	// ------------------------------------------------------------------ ROMs
	logic [10:0] phase_r;
	logic [11:0] cos_q;
	logic [8:0]  vol_ra;
	logic [13:0] vol_q;
	logic [6:0]  pitch_ra;
	logic [29:0] pitch_q;
	logic [8:0]  fine_ra;
	logic [7:0]  fine_q;

	upd933_rom #(.AW(11), .DW(12), .INIT({TABLE_DIR, "upd933_cosine.hex"}))     rom_cos  (.clk(clk), .addr(phase_r),  .q(cos_q));
	upd933_rom #(.AW(9),  .DW(14), .INIT({TABLE_DIR, "upd933_volume.hex"}))     rom_vol  (.clk(clk), .addr(vol_ra),   .q(vol_q));
	upd933_rom #(.AW(7),  .DW(30), .INIT({TABLE_DIR, "upd933_pitch.hex"}))      rom_pit  (.clk(clk), .addr(pitch_ra), .q(pitch_q));
	upd933_rom #(.AW(9),  .DW(8),  .INIT({TABLE_DIR, "upd933_pitch_fine.hex"})) rom_fine (.clk(clk), .addr(fine_ra),  .q(fine_q));

	// ------------------------------------------------------------------ helpers
	function automatic logic [26:0] env_target(input logic [1:0] kind, input logic [6:0] lvl);
		case (kind)
			2'd0:    env_target = {2'b0, lvl, 18'b0};                    // DCA: level << 18
			2'd1:    env_target = {1'b0, lvl, 19'b0};                    // DCW: level << 19
			default: env_target = lvl[6] ? {lvl[5:0], 21'b0}             // DCO: level << 16 (<< 5 more)
			                             : {5'b0, lvl[5:0], 16'b0};
		endcase
	endfunction

	function automatic logic [18:0] env_rate(input logic [6:0] code);
		env_rate = 19'({1'b1, code[2:0]}) << code[6:3];
	endfunction

	function automatic logic [26:0] env_step(input logic dir, input logic [26:0] cur, input logic [26:0] tgt,
	                                         input logic [18:0] rate);
		env_step = cur;
		if (cur != tgt) begin
			if (!dir) begin
				if (cur > tgt || (tgt - cur) <= 27'(rate)) env_step = tgt;
				else env_step = cur + 27'(rate);
			end else begin
				if (cur < tgt || (cur - tgt) <= 27'(rate)) env_step = tgt;
				else env_step = cur - 27'(rate);
			end
		end
	endfunction

	localparam int VOICE_MAP [0:7] = '{5, 0, 7, 2, 1, 4, 3, 6};

	// ------------------------------------------------------------------ chip state
	logic        cs_r, id_r, pend, irq_r;
	logic        tmr_armed;
	logic [39:0] tmr_deadline;
	logic [7:0]  sd0, sd1;
	logic [1:0]  dpos;
	logic [2:0]  scnt;          // m_sample_count & 7
	logic signed [15:0] last;
	logic [31:0] seed;
	logic [39:0] next_bnd;      // tick at which the next sample is computed

	// a >= b for ticks that may wrap: a - b (mod 2^40) in [0, 2^39)
	function automatic logic t_ge(input logic [39:0] a, input logic [39:0] b);
		logic [39:0] d;
		d = a - b;
		return !d[39];
	endfunction

	assign irq = irq_r;
	assign busy = (state != S_IDLE);
	assign settled = (state == S_IDLE) && !req_ack && !t_ge(now_tick, next_bnd) && !(!ext_timer && tmr_armed && t_ge(now_tick, tmr_deadline));

	// ------------------------------------------------------------------ work registers
	logic [2:0]  vi;
	logic [2:0]  vn;
	logic [71:0] ea, ew, eo;
	logic signed [18:0] acc;
	logic [10:0] window_r;
	logic [12:0] dv_rem;
	logic [11:0] dv_d;
	logic [10:0] dv_q;
	logic [3:0]  dv_cnt;
	logic [10:0] dv_add;
	logic signed [15:0] s3, smp;
	logic        dco_chg, pm_chg;
	logic [31:0] lo32;
	// pitch-step routine
	logic [2:0]  ps_v;
	logic        ps_bus;        // 1: called from a register write (ack when done)
	logic [26:0] ps_dco;
	logic        ps_ok;
	// bus
	logic [15:0] val;
	logic [1:0]  bkind;
	logic [2:0]  bv;
	logic [31:0] bd_n, bd_q;
	logic [19:0] bd_r;
	logic [18:0] bd_d;
	logic [5:0]  bd_i;
	logic [3:0]  sc_i;
	logic [29:0] sc_min;
	logic        sc_act;
	logic        rst_bus;       // B_RST: 1 = device reset request (ack), 0 = power-on

	// ------------------------------------------------------------------ shared multiplier
	logic signed [19:0] mul_a;
	logic signed [22:0] mul_b;
	logic signed [42:0] mul_p;

	// current-voice combinational values (E_PH, E_RING)
	logic [10:0] pos;
	logic [2:0]  wave;
	logic [10:0] dcw, pivot;
	logic [9:0]  p10;
	logic [11:0] s1;
	logic signed [15:0] s2;

	always_comb begin
		pos  = v_pos[vn][30:20];
		p10  = pos[9:0];
		wave = v_pos[vn][31] ? v_wave1[vn] : v_wave0[vn];
		dcw  = (11'(ew[56:30] >> 16) < v_dcwlim[vn]) ? 11'(ew[56:30] >> 16) : v_dcwlim[vn];
		pivot = 11'h400 - dcw;
		s1 = mul_p[22:11];
		s2 = 16'({3'b0, mul_p[24:12]}) - 16'({3'b0, vol_q[13:1]});
	end

	always_comb begin
		mul_a = '0;
		mul_b = '0;
		case (state)
			E_PH:    begin mul_a = 20'(pos);              mul_b = 23'(dcw); end
			E_WIN:   begin mul_a = 20'(cos_q);            mul_b = 23'(12'h800 - {1'b0, window_r}); end
			E_VOL:   begin mul_a = 20'(s1);               mul_b = 23'(vol_q); end
			E_RING:  begin mul_a = 20'(last);             mul_b = 23'(s2); end
			E_RAND1: begin mul_a = 20'(seed[15:0]);       mul_b = 23'(LCG_A); end
			E_RAND2: begin mul_a = 20'(seed[31:16]);      mul_b = 23'(LCG_A); end
			P2:      begin mul_a = 20'(pitch_q[29:12]);   mul_b = 23'(fine_q); end
			default: ;
		endcase
	end

	always_ff @(posedge clk) mul_p <= mul_a * mul_b;

	// ------------------------------------------------------------------ transfer function setup
	// mode 0: phase = ph_val; 1: phase = ph_add | (x << k) / d; 2: resonance (multiplier)
	logic [1:0]  ph_mode;
	logic [10:0] ph_val, ph_x, ph_add;
	logic [11:0] ph_d;
	logic [3:0]  ph_k;
	logic [10:0] win;

	always_comb begin
		ph_mode = 2'd0; ph_val = '0; ph_x = '0; ph_d = 12'd1; ph_k = 4'd10; ph_add = '0;
		case (wave)
			3'd0: begin   // sawtooth
				ph_mode = 2'd1;
				if (pos < pivot) begin ph_x = pos; ph_d = 12'(pivot); end
				else begin ph_x = pos - pivot; ph_d = 12'h800 - 12'(pivot); ph_add = 11'h400; end
			end
			3'd1: begin   // square
				if ({1'b0, p10} < pivot) begin ph_mode = 2'd1; ph_x = 11'(p10); ph_d = 12'(pivot); ph_add = {pos[10], 10'b0}; end
				else ph_val = {pos[10], 10'h3ff};
			end
			3'd2: begin   // pulse
				if ({1'b0, pos} < {pivot, 1'b0}) begin ph_mode = 2'd1; ph_x = pos; ph_d = {pivot, 1'b0}; ph_k = 4'd11; end
				else ph_val = 11'h7ff;
			end
			3'd3: ;       // silent
			3'd4: begin   // double sine
				ph_mode = 2'd1; ph_k = 4'd11;
				if (pos < pivot) begin ph_x = pos; ph_d = 12'(pivot); end
				else begin ph_x = pos - pivot; ph_d = 12'h800 - 12'(pivot); end
			end
			3'd5: begin   // saw pulse
				if (!pos[10]) ph_val = pos;
				else if ({1'b0, pos} < 12'(pivot) + 12'h400) begin ph_mode = 2'd1; ph_x = 11'(p10); ph_d = 12'(pivot); ph_add = 11'h400; end
				else ph_val = 11'h7ff;
			end
			3'd6: ph_mode = 2'd2;   // resonance
			3'd7: begin   // double pulse
				if ({1'b0, p10} < pivot) begin ph_mode = 2'd1; ph_x = 11'(p10); ph_d = 12'(pivot); end
				else ph_val = 11'h7ff;
			end
		endcase

		case (v_window[vn])
			3'd0: win = '0;
			3'd1: win = pos;
			3'd2: win = pos[10] ? {p10, 1'b0} : ({p10, 1'b0} ^ 11'h7fe);
			3'd3: win = pos[10] ? {p10, 1'b0} : 11'd0;
			3'd4: win = pos[10] ? 11'h7ff : {p10, 1'b0};
			default: win = {~p10, 1'b0};
		endcase
	end

	// ------------------------------------------------------------------ envelope update (E_MUTE)
	logic [71:0] ecur  [0:2];
	logic [26:0] tgt_n [0:2];
	logic [26:0] cur_n [0:2];
	logic        hit_n [0:2];
	assign ecur[0] = ea;
	assign ecur[1] = ew;
	assign ecur[2] = eo;
	always_comb begin
		for (int k = 0; k < 3; k++) begin
			tgt_n[k] = env_target(2'(k), ecur[k][63:57]);
			cur_n[k] = env_step(ecur[k][71], ecur[k][56:30], tgt_n[k], env_rate(ecur[k][70:64]));
			hit_n[k] = !susf[k*8 + int'(vn)] && (cur_n[k] == tgt_n[k]);
		end
	end

	// envelope register write (B_ENV_LATCH)
	logic [26:0] bw_cur, bw_tgt;
	logic [31:0] bw_rem;
	always_comb begin
		bw_cur = env_q[bkind][56:30];
		bw_tgt = env_target(bkind, val[6:0]);
		bw_rem = val[15] ? (32'(bw_cur) - 32'(bw_tgt)) : (32'(bw_tgt) - 32'(bw_cur));
	end

	// irq_data(): DCO 0-7, then DCW, then DCA
	logic [7:0]  irqd_val;
	logic [4:0]  irqd_bit;
	logic        irqd_any;
	always_comb begin
		irqd_val = 8'h00; irqd_bit = '0; irqd_any = 1'b0;
		for (int i = 7; i >= 0; i--) if (irqf[i])      begin irqd_any = 1'b1; irqd_bit = 5'(i);      irqd_val = 8'(1 | (i << 1)); end
		for (int i = 7; i >= 0; i--) if (irqf[8 + i])  begin irqd_any = 1'b1; irqd_bit = 5'(8 + i);  irqd_val = 8'(2 | (i << 2)); end
		for (int i = 7; i >= 0; i--) if (irqf[16 + i]) begin irqd_any = 1'b1; irqd_bit = 5'(16 + i); irqd_val = 8'(4 | (i << 3)); end
	end

	// scan step for update_pending_irq()
	logic [29:0] sc_min_n;
	logic        sc_act_n;
	always_comb begin
		sc_min_n = sc_min; sc_act_n = sc_act;
		for (int k = 0; k < 3; k++)
			if (!susf[k*8 + int'(sc_i[2:0])]) begin
				sc_act_n = 1'b1;
				if (env_q[k][29:0] < sc_min_n) sc_min_n = env_q[k][29:0];
			end
	end

	wire req_ok = req_valid && !req_ack;
	wire svc_ok = req_ok && !t_ge(req_tick, next_bnd);

	// ------------------------------------------------------------------ main FSM
	always_ff @(posedge clk) begin
		req_ack <= 1'b0;
		irq_evt <= 1'b0;
		sample_valid <= 1'b0;
		timer_arm <= 1'b0;
		timer_cancel <= 1'b0;
		for (int k = 0; k < 3; k++) env_we[k] <= 1'b0;

		// external timer_tick(); the case below does not touch pend/irq while no request is open
		if (ext_timer && timer_fire) begin
			pend <= 1'b1;
			if ((cs_r & id_r) != irq_r) begin irq_r <= cs_r & id_r; irq_evt <= 1'b1; irq_evt_tick <= timer_fire_tick; end
		end

		case (state)
		// ============================================================= idle / dispatch
		S_IDLE: begin
			if (svc_ok) begin
				if (!t_ge(req_tick + TPS, next_bnd)) late <= 1'b1;
				if (!ext_timer && tmr_armed && t_ge(req_order, tmr_deadline)) begin
					// timer_tick() first
					tmr_armed <= 1'b0;
					pend <= 1'b1;
					if ((cs_r & id_r) != irq_r) begin irq_r <= cs_r & id_r; irq_evt <= 1'b1; irq_evt_tick <= tmr_deadline; end
				end else begin
					case (req_op)
					OP_WR: begin
						if (cs_r) req_ack <= 1'b1;
						else if (dpos != 2'd2) begin
							if (dpos == 2'd0) sd0 <= req_data; else sd1 <= req_data;
							dpos <= dpos + 2'd1;
							req_ack <= 1'b1;
						end else begin
							dpos <= 2'd0;
							val <= {sd1, req_data};
							bv <= sd0[2:0];
							case (sd0[7:3])
							5'h00, 5'h02, 5'h04: begin
								bkind <= (sd0[7:3] == 5'h00) ? 2'd0 : (sd0[7:3] == 5'h04) ? 2'd1 : 2'd2;
								env_ra <= sd0[2:0];
								state <= B_ENV_WAIT;
							end
							5'h0c: begin
								v_pitch[sd0[2:0]] <= {sd1, req_data};
								env_ra <= sd0[2:0];
								ps_v <= sd0[2:0];
								ps_bus <= 1'b1;
								state <= B_PITCH_WAIT;
							end
							5'h0d: begin
								v_wave0[sd0[2:0]] <= sd1[7:5];
								v_wave1[sd0[2:0]] <= sd1[1] ? sd1[4:2] : sd1[7:5];
								v_window[sd0[2:0]] <= {sd1[0], req_data[7:6]};
								if (!sd0[0]) begin
									v_ring[sd0[2:0] + 3'd6] <= req_data[5];
									v_pmod[sd0[2:0] + 3'd6] <= req_data[4:3];
									v_mute[sd0[2:0] + 3'd6] <= req_data[2];
								end
								req_ack <= 1'b1;
							end
							5'h13: begin
								v_pos[sd0[2:0]] <= {sd1, req_data, 16'b0};
								req_ack <= 1'b1;
							end
							5'h17: begin
								if (!sd0[2]) v_pm[{sd0[1:0], 1'b0}] <= {sd1, req_data};
								req_ack <= 1'b1;
							end
							default: req_ack <= 1'b1;
							endcase
						end
					end
					OP_RD: begin
						if (cs_r) rd_data <= 8'hff;
						else begin
							rd_data <= irqd_val;
							if (irqd_any) irqf[irqd_bit] <= 1'b0;
						end
						req_ack <= 1'b1;
					end
					OP_CS: begin
						if (!cs_r && req_data[0]) begin
							// update_pending_irq()
							pend <= 1'b0;
							if (|irqf) begin
								tmr_armed <= 1'b1;
								tmr_deadline <= req_tick;
								timer_arm <= 1'b1;
								timer_n <= 32'd0;
								cs_r <= 1'b1;
								if ((1'b1 & id_r & 1'b0) != irq_r) begin irq_r <= 1'b0; irq_evt <= 1'b1; irq_evt_tick <= req_tick; end
								req_ack <= 1'b1;
							end else begin
								sc_i <= '0;
								sc_min <= '1;
								sc_act <= 1'b0;
								state <= B_SCAN_RD;
							end
						end else begin
							cs_r <= req_data[0];
							if ((req_data[0] & id_r & pend) != irq_r) begin
								irq_r <= req_data[0] & id_r & pend; irq_evt <= 1'b1; irq_evt_tick <= req_tick;
							end
							req_ack <= 1'b1;
						end
					end
					OP_ID: begin
						id_r <= req_data[0];
						if ((cs_r & req_data[0] & pend) != irq_r) begin
							irq_r <= cs_r & req_data[0] & pend; irq_evt <= 1'b1; irq_evt_tick <= req_tick;
						end
						req_ack <= 1'b1;
					end
					OP_RESET: begin
						// device_reset(); /CS and /ID keep their levels
						pend <= 1'b0;
						if (irq_r) begin irq_r <= 1'b0; irq_evt <= 1'b1; irq_evt_tick <= req_tick; end
						tmr_armed <= 1'b0;
						timer_cancel <= 1'b1;
						dpos <= '0; sd0 <= '0; sd1 <= '0;
						scnt <= '0;
						last <= '0;
						irqf <= '0;
						susf <= '1;
						for (int i = 0; i < 8; i++) begin
							v_wave0[i] <= '0; v_wave1[i] <= '0; v_window[i] <= '0; v_ring[i] <= '0;
							v_pmod[i] <= '0; v_mute[i] <= '0; v_pitch[i] <= '0; v_pm[i] <= '0;
							v_pos[i] <= '0; v_step[i] <= '0; v_dcwlim[i] <= '0;
						end
						sc_i <= '0;
						rst_bus <= 1'b1;
						state <= B_RST;
					end
					default: req_ack <= 1'b1;
					endcase
				end
			end else if (t_ge(now_tick, next_bnd) || (req_ok && t_ge(req_tick, next_bnd))) begin
				// a pending request at or past the boundary needs this sample (request ticks never
				// decrease, so every later request needs it too)
				vi <= '0;
				acc <= '0;
				state <= E_RD;
			end else if (!ext_timer && tmr_armed && t_ge(now_tick, tmr_deadline) && !(req_ok && !t_ge(req_order, tmr_deadline))) begin
				tmr_armed <= 1'b0;
				pend <= 1'b1;
				if ((cs_r & id_r) != irq_r) begin irq_r <= cs_r & id_r; irq_evt <= 1'b1; irq_evt_tick <= tmr_deadline; end
			end
		end

		// ============================================================= sample engine
		E_RD: begin
			vn <= 3'(VOICE_MAP[vi]);
			env_ra <= 3'(VOICE_MAP[vi]);
			state <= E_WAIT;
		end
		E_WAIT: state <= E_LATCH;
		E_LATCH: begin
			ea <= env_q[0]; ew <= env_q[1]; eo <= env_q[2];
			vol_ra <= env_q[0][54:46];          // DCA current >> 16
			state <= E_PH;
		end
		E_PH: begin
			window_r <= win;
			case (ph_mode)
				2'd0: begin phase_r <= ph_val; state <= E_COS; end
				2'd1: begin
					dv_rem <= 13'(ph_x); dv_d <= ph_d; dv_q <= '0; dv_cnt <= ph_k; dv_add <= ph_add;
					state <= E_DIV;
				end
				default: state <= E_RES;
			endcase
		end
		E_RES: begin
			phase_r <= 11'(pos + 11'(mul_p[20:6]));
			state <= E_COS;
		end
		E_DIV: begin : b_ediv
			logic [12:0] r2;
			logic        ge;
			r2 = {dv_rem[11:0], 1'b0};
			ge = (r2 >= 13'(dv_d));
			dv_rem <= ge ? r2 - 13'(dv_d) : r2;
			dv_q <= {dv_q[9:0], ge};
			dv_cnt <= dv_cnt - 4'd1;
			if (dv_cnt == 4'd1) begin
				phase_r <= dv_add | {dv_q[9:0], ge};
				state <= E_COS;
			end
		end
		E_COS: state <= E_WIN;                 // cosine ROM read
		E_WIN: state <= E_VOL;                 // cos * (0x800 - window)
		E_VOL: state <= E_RING;                // (..>>11) * volume
		E_RING: begin
			if (v_ring[vn]) state <= E_RING2;    // s2 * last
			else begin s3 <= s2; state <= E_MUTE; end
		end
		E_RING2: begin : b_ering2
			logic signed [42:0] p;
			p = mul_p[42] ? mul_p + 43'sd4095 : mul_p;
			s3 <= 16'(p >>> 12);
			state <= E_MUTE;
		end
		E_MUTE: begin
			smp <= v_mute[vn] ? s3 - last : s3;
			// envelopes: DCA, DCW, DCO update()
			for (int k = 0; k < 3; k++) begin
				env_we[k] <= 1'b1;
				env_wd[k] <= {ecur[k][71:57], cur_n[k], (ecur[k][29:0] == 30'd0) ? 30'd0 : ecur[k][29:0] - 30'd1};
				if (hit_n[k]) begin irqf[k*8 + int'(vn)] <= 1'b1; susf[k*8 + int'(vn)] <= 1'b1; end
			end
			env_wa <= vn;
			dco_chg <= ((eo[56:30] ^ cur_n[2]) >> 11) != 27'd0;
			ps_dco <= cur_n[2];
			if (scnt == 3'd0 && v_pmod[vn] == 2'd3) state <= E_RAND1;
			else begin : b_npm
				logic [15:0] npm;
				npm = (scnt != 3'd0) ? v_pm[vn] : (v_pmod[vn] == 2'd2) ? last : 16'd0;
				pm_chg <= npm != v_pm[vn];
				v_pm[vn] <= npm;
				state <= E_CHK;
			end
		end
		E_RAND1: state <= E_RAND2;             // seed[15:0] * A
		E_RAND2: begin                         // seed[31:16] * A
			lo32 <= mul_p[31:0];
			state <= E_RAND3;
		end
		E_RAND3: begin : b_erand3
			logic [31:0] ns;
			logic [15:0] npm;
			ns = lo32 + {mul_p[15:0], 16'b0} + LCG_C;
			seed <= ns;
			npm = ns[30] ? 16'h4000 : 16'h0000;   // rand() & (32 << 9): bit 14 of the rotated value
			pm_chg <= npm != v_pm[vn];
			v_pm[vn] <= npm;
			state <= E_CHK;
		end
		E_CHK: begin
			if (dco_chg || pm_chg) begin
				ps_v <= vn;
				ps_bus <= 1'b0;
				state <= P0;
			end else state <= E_WB;
		end
		E_WB: begin
			v_pos[vn] <= v_pos[vn] + v_step[vn];
			last <= smp;
			if (vi == 3'd7) begin : b_ewb
				logic signed [18:0] sum;
				sum = acc + 19'(smp);
				sample_sum <= sum;
				sample_out <= (sum > 19'sd32767) ? 16'sh7fff : (sum < -19'sd32768) ? -16'sh8000 : 16'(sum);
				sample_valid <= 1'b1;
				scnt <= scnt + 3'd1;
				next_bnd <= next_bnd + TPS;
				state <= S_IDLE;
			end else begin
				acc <= acc + 19'(smp);
				vi <= vi + 3'd1;
				state <= E_RD;
			end
		end

		// ============================================================= update_pitch_step()
		P0: begin : b_p0
			logic signed [18:0] p;
			p = 19'(v_pitch[ps_v]) + 19'(ps_dco[26:11]) + 19'($signed(v_pm[ps_v]));
			ps_ok <= (p[18:16] == 3'd0) && (p[15:0] != 16'd0);
			pitch_ra <= p[15:9];
			fine_ra <= p[8:0];
			state <= P1;
		end
		P1: state <= P2;                       // ROM read
		P2: state <= P3;                       // (step >> 12) * fine
		P3: begin : b_p3
			logic [31:0] st;
			st = ps_ok ? 32'(pitch_q) + mul_p[31:0] : 32'd0;
			v_step[ps_v] <= st;
			v_dcwlim[ps_v] <= (st[31:18] >= 14'h400) ? 11'd0 : 11'h400 - 11'(st[31:18]);
			if (ps_bus) begin req_ack <= 1'b1; state <= S_IDLE; end
			else state <= E_WB;
		end

		// ============================================================= register writes
		B_ENV_WAIT: state <= B_ENV_LATCH;
		B_ENV_LATCH: begin
			// countdown = ceil(remaining / rate), remaining as MAME's unsigned subtraction
			bd_n <= bw_rem;
			bd_d <= env_rate(val[14:8]);
			bd_r <= '0;
			bd_q <= '0;
			bd_i <= '0;
			state <= B_ENV_DIV;
		end
		B_ENV_DIV: begin : b_envdiv
			logic [19:0] r2;
			logic        ge;
			r2 = {bd_r[18:0], bd_n[31]};
			ge = r2 >= 20'(bd_d);
			bd_r <= ge ? r2 - 20'(bd_d) : r2;
			bd_q <= {bd_q[30:0], ge};
			bd_n <= {bd_n[30:0], 1'b0};
			bd_i <= bd_i + 6'd1;
			if (bd_i == 6'd31) state <= B_ENV_WR;
		end
		B_ENV_WR: begin
			env_we[bkind] <= 1'b1;
			env_wa <= bv;
			env_wd[bkind] <= {val[15], val[14:8], val[6:0], bw_cur, 30'(bd_q) + 30'(bd_r != 20'd0)};
			irqf[bkind*8 + int'(bv)] <= 1'b0;
			susf[bkind*8 + int'(bv)] <= val[7];
			req_ack <= 1'b1;
			state <= S_IDLE;
		end
		B_PITCH_WAIT: state <= B_PITCH_LATCH;
		B_PITCH_LATCH: begin
			ps_dco <= env_q[2][56:30];
			state <= P0;
		end

		// ============================================================= /CS rising: update_pending_irq()
		B_SCAN_RD: begin env_ra <= sc_i[2:0]; state <= B_SCAN_WAIT; end
		B_SCAN_WAIT: state <= B_SCAN_USE;
		B_SCAN_USE: begin
			sc_min <= sc_min_n;
			sc_act <= sc_act_n;
			sc_i <= sc_i + 4'd1;
			state <= (sc_i == 4'd7) ? B_SCAN_DONE : B_SCAN_RD;
		end
		B_SCAN_DONE: begin
			tmr_armed <= sc_act;
			timer_arm <= sc_act;
			timer_cancel <= !sc_act;
			timer_n <= {2'b0, sc_min};
			// new_time * 250 = (n << 8) - (n << 2) - (n << 1)
			tmr_deadline <= req_tick + ({10'b0, sc_min} << 8) - ({10'b0, sc_min} << 2) - ({10'b0, sc_min} << 1);
			cs_r <= 1'b1;
			if (irq_r) begin irq_r <= 1'b0; irq_evt <= 1'b1; irq_evt_tick <= req_tick; end
			req_ack <= 1'b1;
			state <= S_IDLE;
		end

		// ============================================================= clear envelope RAMs
		B_RST: begin
			for (int k = 0; k < 3; k++) begin env_we[k] <= 1'b1; env_wd[k] <= '0; end
			env_wa <= sc_i[2:0];
			sc_i <= sc_i + 4'd1;
			if (sc_i == 4'd7) begin
				if (rst_bus) req_ack <= 1'b1;
				state <= S_IDLE;
			end
		end

		default: state <= S_IDLE;
		endcase

		if (rst) begin
			state <= B_RST;
			rst_bus <= 1'b0;
			sc_i <= '0;
			next_bnd <= now_tick;     // sample k at t0 + 250 k (t0 = 0 on the board)
			cs_r <= 1'b1; id_r <= 1'b1; pend <= 1'b0; irq_r <= 1'b0;
			tmr_armed <= 1'b0; tmr_deadline <= '0;
			timer_arm <= 1'b0; timer_cancel <= 1'b0; timer_n <= '0;
			dpos <= '0; sd0 <= '0; sd1 <= '0;
			scnt <= '0; last <= '0;
			seed <= RAND_SEED;
			irqf <= '0; susf <= '1;
			late <= 1'b0;
			req_ack <= 1'b0; irq_evt <= 1'b0; irq_evt_tick <= '0; sample_valid <= 1'b0;
			rd_data <= '0; sample_sum <= '0; sample_out <= '0;
			for (int i = 0; i < 8; i++) begin
				v_wave0[i] <= '0; v_wave1[i] <= '0; v_window[i] <= '0; v_ring[i] <= '0;
				v_pmod[i] <= '0; v_mute[i] <= '0; v_pitch[i] <= '0; v_pm[i] <= '0;
				v_pos[i] <= '0; v_step[i] <= '0; v_dcwlim[i] <= '0;
			end
		end
	end

endmodule

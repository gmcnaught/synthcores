#!/usr/bin/env python3
"""64 kHz -> 48 kHz resampler for the SC-55's output (hdl/board/resample.sv).

Polyphase FIR for L = 3 (up), M = 4 (down): a Kaiser-windowed sinc at
fs = 192 kHz, cut-off 20 kHz, TAPS taps (TAPS / 3 per phase), coefficients
signed Q1.17. Output m uses phase p = (4 m) mod 3 and input n0 = floor(4 m / 3):
    y[m] = sum_j h[3 j + p] * x[n0 - j]     (x the 64 kHz samples, newest first)
with the integer arithmetic of the HDL (see model()).

  gen_resampler.py            write hdl/board/resample_coef.svh
  gen_resampler.py --check    print the response at a few frequencies
"""
import math
import pathlib
import sys

TAPS = 192
PH = TAPS // 3
FS = 192_000.0
FC = 20_000.0
BETA = 8.0
QBITS = 17
ROOT = pathlib.Path(__file__).resolve().parent.parent


def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


def coefficients():
    h = []
    for n in range(TAPS):
        m = n - (TAPS - 1) / 2
        sinc = 2 * FC / FS if m == 0 else math.sin(2 * math.pi * FC / FS * m) / (math.pi * m)
        w = i0(BETA * math.sqrt(1 - (2 * n / (TAPS - 1) - 1) ** 2)) / i0(BETA)
        h.append(3 * sinc * w)                     # gain 3 for the zero-stuffing
    return [round(v * (1 << QBITS)) for v in h]


def model(x, h):
    """Integer model: x are 16-bit samples (one channel); returns the 48 kHz outputs."""
    out, hist = [], []
    for n, v in enumerate(x):
        hist.insert(0, v)
        del hist[PH:]
        if n % 4 == 3:
            continue
        p = n % 4                                  # outputs at n = 4k, 4k+1, 4k+2 with phases 0, 1, 2
        acc = sum(h[3 * j + p] * hist[j] for j in range(len(hist)))
        y = acc >> QBITS
        out.append(max(-32768, min(32767, y)))
    return out


def response(h, f):
    re = sum(c * math.cos(2 * math.pi * f / FS * n) for n, c in enumerate(h))
    im = sum(c * math.sin(2 * math.pi * f / FS * n) for n, c in enumerate(h))
    return 20 * math.log10(max(1e-12, math.hypot(re, im) / (3 << QBITS)))


def main() -> int:
    h = coefficients()
    if "--check" in sys.argv:
        for f in (1000, 10000, 16000, 18000, 20000, 22000, 24000, 28000, 32000, 40000):
            print(f"{f:6d} Hz {response(h, f):7.1f} dB")
        return 0
    lines = ["// Generated by tools/gen_resampler.py; do not edit.",
             f"// {TAPS} taps (Kaiser beta {BETA}, cut-off {FC:.0f} Hz at {FS:.0f} Hz), Q1.{QBITS}",
             "case (idx)"]
    for n, c in enumerate(h):
        lines.append(f"    8'd{n}: return {'-' if c < 0 else ''}18'sd{abs(c)};")
    lines += ["    default: return 18'sd0;", "endcase", ""]
    (ROOT / "hdl" / "board" / "resample_coef.svh").write_text("\n".join(lines))
    print("wrote hdl/board/resample_coef.svh")
    return 0


if __name__ == "__main__":
    sys.exit(main())

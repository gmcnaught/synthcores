#!/usr/bin/env python3
"""Generate hdl/pcm/sc55_pcm_interp.svh from the reference model's interp_lut (pcm.cpp).

Usage: gen_pcm_tables.py [PCM_CPP] [OUT_SVH]
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party" / "nuked-sc55" / "src" / "backend" / "pcm.cpp"
OUT = ROOT / "hdl" / "pcm" / "sc55_pcm_interp.svh"


def main() -> int:
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else SRC
    out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else OUT
    text = src.read_text()
    m = re.search(r"static const int interp_lut\[3\]\[128\] = \{(.*?)\n\};", text, re.S)
    body = m.group(1)
    tables = [list(map(int, re.findall(r"\d+", blk))) for blk in re.findall(r"\{([^{}]*)\}", body)]
    assert len(tables) == 3 and all(len(t) == 128 for t in tables), [len(t) for t in tables]
    lines = ["// Generated by tools/gen_pcm_tables.py from pcm.cpp interp_lut; do not edit.",
             "case ({t, i})"]
    for ti, tab in enumerate(tables):
        for i, v in enumerate(tab):
            lines.append(f"    {{2'd{ti}, 7'd{i}}}: return 12'd{v};")
    lines += ["    default: return 12'd0;", "endcase", ""]
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({sum(map(len, tables))} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

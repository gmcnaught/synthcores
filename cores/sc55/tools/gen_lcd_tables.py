#!/usr/bin/env python3
"""Generate the LCD tables from the reference model's headers:

  hdl/board/lcd_font.svh  lcd_font[240][10] (5x8 character rows) as a case table
  hdl/board/lcd_back.hex  the 741 x 268 background (lcd_back.h back_data, 1 bit
                          per pixel, 0 = palette[0] blue, 1 = palette[1] black),
                          row-major pixel p = y * 741 + x in bit p % 8 of byte
                          p / 8, one byte per line for $readmemh

Usage: gen_lcd_tables.py [BACKEND_DIR] [OUT_DIR]
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party" / "nuked-sc55" / "src" / "backend"
OUT = ROOT / "hdl" / "board"                                              # lcd_back.hex (SC-55 only)
FONT_OUT = ROOT.parent.parent / "modules" / "roland" / "hdl" / "board"   # lcd_font.svh (shared with the JV-880)
W, H = 741, 268


def main() -> int:
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else SRC
    out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else OUT
    font_out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else FONT_OUT

    font_txt = (src / "lcd_font.h").read_text()
    rows = re.findall(r"\{([^{}]*)\}", font_txt.split("=", 1)[1])
    font = [[int(v, 0) for v in r.split(",") if v.strip()] for r in rows]
    assert len(font) == 240 and all(len(r) == 10 for r in font), (len(font), {len(r) for r in font})
    lines = ["// Generated by tools/gen_lcd_tables.py from lcd_font.h; do not edit.",
             "// font_row(ch - 16, row): 5 dots, bit 4 = leftmost",
             "case ({fc, fr})"]
    for c, r in enumerate(font):
        for i, v in enumerate(r):
            if v:
                lines.append(f"    {{8'd{c}, 4'd{i}}}: return 5'h{v & 0x1f:02x};")
    lines += ["    default: return 5'h00;", "endcase", ""]
    (font_out / "lcd_font.svh").write_text("\n".join(lines))

    back_txt = (src / "lcd_back.h").read_text()
    pal = re.search(r"back_palette\[\]\s*=\s*\{([^}]*)\}", back_txt).group(1)
    pal = [int(v, 0) for v in pal.split(",") if v.strip()]
    assert pal == [0xff0f6fff, 0xff000000], [hex(p) for p in pal]
    data = re.search(r"back_data\[\]\s*=\s*\{([^}]*)\}", back_txt, re.S).group(1)
    data = [int(v) for v in re.findall(r"\d+", data)]
    assert len(data) == W * H and set(data) <= {0, 1}, (len(data), set(data))
    data += [0] * (-len(data) % 8)
    packed = [sum(data[i + b] << b for b in range(8)) for i in range(0, len(data), 8)]
    (out / "lcd_back.hex").write_text("\n".join(f"{v:02x}" for v in packed) + "\n")
    print(f"wrote {font_out / 'lcd_font.svh'} and {out / 'lcd_back.hex'} ({len(data)} pixels)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

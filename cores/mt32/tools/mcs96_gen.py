"""Generate the MCS-96 decode ROM from Nuked-MT32's copy of MAME's mcs96 core.

    mcs96_gen.py [OUTDIR]     (default hdl/mcs96)

Reads modules/nuked-mt32/mame/i8x9x.hxx (which handler runs for each inst_state: 0x000-0x0ff
plain opcodes, 0x100-0x1ff after the FE prefix) and mcs96.hxx (the handlers' bodies, for the
cycle counts). Writes:
  mcs96_decode.hex   512 words, one per inst_state (fields below)
  mcs96_decode.svh   localparams for the mnemonic and addressing-mode codes
  mcs96_decode.txt   the table in words

Word layout (32 bits):
  [31]    valid (the reference has a handler; xch/xchb have empty bodies and count as invalid)
  [30]    noirq (the handler ends in next_noirq: the next fetch does not take interrupts)
  [29:24] cycles when OPI bit 0 is clear after the operand fetch (or: branch not taken)
  [23:18] cycles when OPI bit 0 is set (or: branch taken)
  [17:14] addressing mode (AM_*)
  [13:12] operand count of the mode name (1, 2, 3; 0 for none and the relative modes)
  [11]    immediate is a word (immed_1w/2w/3w)
  [10:4]  mnemonic (MN_*)
  [3:0]   0
Cycle counts are in CPU cycles, as next() takes them (the core multiplies by cycles_scaling, 3).
Shifts (OP1 ? 7 + OP1 : 8) and norml (11 + OP3) are computed by the core; their fields are 0.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
MAME = ROOT / "modules" / "nuked-mt32" / "mame"

MODES = ["none", "direct", "immed", "indirect", "indexed", "rel8", "rel11", "rel16", "rrel8",
         "immed_or_reg", "indirect_1n"]


def split_mode(func):
    m = re.match(r"(\w+?)_(direct|immed_or_reg|immed|indirect|indexed)_(\d)([bwen])$", func)
    if m:
        mn, am, n, w = m.groups()
        if am == "indirect" and n == "1" and w == "n":
            return mn, "indirect_1n", 1, False
        return mn, am, int(n), am == "immed" and w == "w"
    m = re.match(r"(\w+?)_(rel8|rel11|rel16|rrel8|brrel8|wrrel8)$", func)
    if m:
        am = m.group(2)
        return m.group(1), "rrel8" if am in ("rrel8", "brrel8", "wrrel8") else am, 0, False
    m = re.match(r"(\w+)_none$", func)
    if m:
        return m.group(1), "none", 0, False
    raise ValueError(func)


def cycles(body):
    """(even, odd, noirq) from a handler body; None for the computed ones."""
    noirq = "next_noirq(" in body
    ns = re.findall(r"next(?:_noirq)?\(([^;]*)\);", body)
    if not ns:
        return None
    if any("OP1 ? 7+OP1" in n or "11+OP3" in n for n in ns):
        return (0, 0, noirq)
    m = re.fullmatch(r"OPI & 0x01 \? (\d+) : (\d+)", ns[0])
    if len(ns) == 1 and m:
        return (int(m.group(2)), int(m.group(1)), noirq)
    if all(re.fullmatch(r"\d+", n) for n in ns):
        vals = [int(n) for n in ns]
        if len(vals) == 1:
            return (vals[0], vals[0], noirq)
        if len(vals) == 2:
            # post_indirect: if(OPI & 0x01) { ...; next(A); } else { next(B); }  -> odd A, even B
            # branches:      if(cond) { PC += OP1; next(T); } else { next(N); }     -> taken T, not N
            # Both are written "first = odd/taken, second = even/not taken".
            return (vals[1], vals[0], noirq)
    raise ValueError(body)


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "hdl" / "mcs96"
    out.mkdir(parents=True, exist_ok=True)
    bodies = dict(re.findall(r"void mcs96_device::(\w+)_full\(\)\n\{\n(.*?)\n\}\n",
                             (MAME / "mcs96.hxx").read_text(), re.S))
    disp = dict((int(s, 16), f) for s, f in
                re.findall(r"case 0x([0-9a-f]+): (\w+)_full\(\); break;", (MAME / "i8x9x.hxx").read_text()) if int(s, 16) < 512)
    mnems = sorted({split_mode(f)[0] for f in disp.values()} | {"xch", "xchb"})
    words, text = [], []
    for st in range(512):
        f = disp.get(st)
        if f is None:
            words.append(0)
            text.append(f"{st:03x}  -")
            continue
        mn, am, n, immw = split_mode(f)
        cy = cycles(bodies[f])
        valid = cy is not None
        ce, co, noirq = cy if valid else (0, 0, False)
        assert ce < 64 and co < 64
        w = (valid << 31) | (noirq << 30) | (ce << 24) | (co << 18) | (MODES.index(am) << 14) | \
            (n << 12) | (immw << 11) | (mnems.index(mn) << 4)
        words.append(w)
        text.append(f"{st:03x}  {mn:6} {am:12} n{n} {'w' if immw else ' '} cyc {ce:2}/{co:2}"
                    f"{' noirq' if noirq else ''}{'' if valid else '  INVALID (empty body)'}")
    (out / "mcs96_decode.hex").write_text("".join(f"{w:08x}\n" for w in words))
    (out / "mcs96_decode.txt").write_text(
        "# Generated by tools/mcs96_gen.py from modules/nuked-mt32/mame (MAME mcs96, BSD-3-Clause)\n"
        "# inst_state  mnemonic  mode  operands  word-immediate  cycles even/odd (not taken/taken)\n"
        + "\n".join(text) + "\n")
    sv = ["// Generated by tools/mcs96_gen.py; do not edit.", "// SPDX-License-Identifier: MIT"]
    sv += [f"localparam logic [3:0] AM_{m.upper()} = 4'd{i};" for i, m in enumerate(MODES)]
    sv += [f"localparam logic [6:0] MN_{m.upper()} = 7'd{i};" for i, m in enumerate(mnems)]
    (out / "mcs96_decode.svh").write_text("\n".join(sv) + "\n")


if __name__ == "__main__":
    main()

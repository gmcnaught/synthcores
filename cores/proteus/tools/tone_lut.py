#!/usr/bin/env python3
"""Coefficients of the inferred per-voice tone filter, and the HDL table generated from them.

The firmware writes a 3-bit tone value into bits 23..21 of the pitch register (+0x04): the
instrument's base (4 for the "Dark" instruments, 0 otherwise) or, at or above the sample's root,
one step per 5 semitones of upward transposition (max 5). That pattern points to a filter
defined in the sample's own frequency terms (an anti-aliasing / interpolation filter), so the
model is [I]:

  one-pole low-pass, cutoff = 0.5 * 2^(-5 * tone / 12) cycles per source word
  -> per output sample: fc = cutoff * |increment|, alpha = 1 - exp(-2 pi fc)

alpha is 12-bit (4096 = pass-through), looked up by tone and a floating-point bucket of
|increment| (3-bit mantissa), so the MAME device, tools/proteus_model.py and the HDL use the
same table. The real chip's response is unknown; this reproduces "darker" instruments and the
transposition rule, not measured hardware.

Usage: tone_lut.py OUT.sv   (writes mister/rtl/tone_lut.sv)
"""
import math
import sys

ENTRIES = 1024  # index = {tone[2:0], e[3:0], m[2:0]}


def index(tone, mag):
    """Table index for tone 0..7 and |increment| 0..0x1FFFF (12 fraction bits)."""
    if mag < 8:
        e, m = 0, mag
    else:
        p = mag.bit_length() - 1  # 3..16
        e = p - 2                 # 1..14
        m = (mag >> (p - 3)) & 7
    return (tone << 7) | (e << 3) | m


def alpha(idx):
    tone, e, m = idx >> 7, (idx >> 3) & 15, idx & 7
    if tone == 0 or e == 15:
        return 4096
    rep = (m + 0.5) if e == 0 else (8 + m + 0.5) * 2 ** (e - 1)  # bucket centre, words * 4096
    fc = 0.5 * 2 ** (-5 * tone / 12) * rep / 4096                  # cycles per output sample
    return max(0, min(4096, round(4096 * (1 - math.exp(-2 * math.pi * fc)))))


TABLE = [alpha(i) for i in range(ENTRIES)]


def write_sv(path):
    lines = [
        "// Generated by tools/tone_lut.py - do not edit.",
        "// Tone filter coefficient (12-bit alpha, 4096 = pass-through) by {tone, |increment| bucket}.",
        "module tone_lut",
        "(",
        "\tinput             clk,",
        "\tinput       [9:0] idx,",
        "\toutput reg [12:0] alpha",
        ");",
        "always @(posedge clk) begin",
        "\tcase (idx)",
    ]
    for i, a in enumerate(TABLE):
        if a != 4096:
            lines.append(f"\t10'd{i}: alpha <= 13'd{a};")
    lines += ["\tdefault: alpha <= 13'd4096;", "\tendcase", "end", "endmodule", ""]
    open(path, "w").write("\n".join(lines))


if __name__ == "__main__":
    write_sv(sys.argv[1] if len(sys.argv) > 1 else "mister/rtl/tone_lut.sv")
    for t in range(8):
        print(t, [TABLE[index(t, 0x1000)], TABLE[index(t, 0x800)], TABLE[index(t, 0x2000)]],
              f"cutoff at root {0.5 * 2 ** (-5 * t / 12) * 39062.5:7.0f} Hz")

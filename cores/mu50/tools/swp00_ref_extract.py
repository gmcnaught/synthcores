#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Copy MAME's SWP00 model into a plain C++ class (cores/mu50/ref/swp00_ref.{h,cpp}).

Usage: swp00_ref_extract.py MAME_DIR OUT_DIR

The class is the U3 reference: the HDL bench runs it beside the HDL. Its synthesis code is
MAME's swp00.cpp verbatim (BSD-3-Clause, Olivier Galibert), taken by function name, so the copy
follows the MAME checkout in cores/mu50/mame/patches/BASE. Only the device glue is replaced: the
wave ROM is an array (24-bit addresses, mirrored every 4 MB, little-endian words, as MAME's
device_rom_interface<24, 0, 0, LITTLE> on a 4 MB region), the stream is `generate(count, out)`,
and the address map becomes write()/read() with the same decode as swp00_device::map().
"""
import re
import sys
from pathlib import Path

HEADER = """// license:BSD-3-Clause
// copyright-holders:Olivier Galibert
// Yamaha SWP00 sound model: MAME's swp00 (src/devices/sound/swp00.cpp/.h) as a plain C++ class,
// for the MU50 core's U3 bench. Generated by cores/mu50/tools/swp00_ref_extract.py; do not edit.
// The synthesis is MAME's code; only the device glue (stream, map, save states) is replaced.
#ifndef SWP00_REF_H
#define SWP00_REF_H

#include <algorithm>
#include <array>
#include <cstdint>
#include <string>
#include <tuple>
#include <utility>

namespace swp00ref {
using u8 = uint8_t; using u16 = uint16_t; using u32 = uint32_t; using u64 = uint64_t;
using s8 = int8_t; using s16 = int16_t; using s32 = int32_t; using s64 = int64_t;
using offs_t = u32;
template<typename T> constexpr bool BIT(T x, int n) { return (x >> n) & 1; }
namespace util { template<typename T> constexpr T make_bitmask(unsigned n) { return n >= 8*sizeof(T) ? T(~T(0)) : T((T(1) << n) - 1); } }

class swp00_ref {
public:
\texplicit swp00_ref(const u8 *wave_rom) { m_wave.rom = wave_rom; reset(); }
\tvoid reset();
\t// one byte to register 000-7FF, decoded as MAME's swp00_device::map()
\tvoid write(u16 reg, u8 data);
\tu8 read(u16 reg);
\t// count sample pairs, L then R, clamped to 18 bits as MAME's put_int_clamp(x >> 6, 0x20000)
\tvoid generate(int count, s32 *out);
\tu32 sample_counter() const { return m_sample_counter; }
\t// bench hook: the seven voice sums of every sample, before the MEG (dry_l, dry_r, rev,
\t// cho_l, cho_r, var_l, var_r)
\tvoid (*m_mix_hook)(void *, const s32 *) = nullptr;
\tvoid *m_mix_ctx = nullptr;

private:
\tstruct wave_access_cache {
\t\tconst u8 *rom;
\t\tu8 read_byte(u32 a) const { return rom[a & 0x3fffff]; }
\t\tu16 read_word(u32 a) const { return read_byte(a) | (read_byte(a + 1) << 8); }
\t};
\twave_access_cache m_wave;

public:
"""

DISPATCH = """
// Register dispatch, as swp00_device::map(): channel registers sss sscc cccs, the control page
// 000-03F, MEG offsets 180-1FF and constants 200-37F (later map entries override earlier ones).
static int chan_index(u16 a) { return ((a >> 5) & 0x3e) | (a & 1); }

void swp00_ref::write(u16 a, u8 data)
{
\ta &= 0x7ff;
\tif(a >= 0x180 && a < 0x200) { offset_w(a - 0x180, data); return; }
\tif(a >= 0x200 && a < 0x380) { const_w(a - 0x200, data); return; }
\tif(a < 0x40) {
\t\tswitch(a) {
\t\tcase 0x01: state_adr_w(data); break;
\t\tcase 0x02: waverom_access_w(data); break;
\t\tcase 0x04: meg_control_w(data); break;
\t\tcase 0x08: keyon_w<3>(data); break;
\t\tcase 0x09: keyon_w<2>(data); break;
\t\tcase 0x0a: keyon_w<1>(data); break;
\t\tcase 0x0b: keyon_w<0>(data); break;
\t\t}
\t\treturn;
\t}
\toffs_t o = a & 0x3e;
\tswitch(chan_index(a)) {
%(w)s\t}
}

u8 swp00_ref::read(u16 a)
{
\ta &= 0x7ff;
\tif(a >= 0x180 && a < 0x200) return offset_r(a - 0x180);
\tif(a >= 0x200 && a < 0x380) return const_r(a - 0x200);
\tif(a < 0x40) {
\t\tswitch(a) {
\t\tcase 0x01: return state_r();
\t\tcase 0x02: return waverom_access_r();
\t\tcase 0x03: return waverom_val_r();
\t\tcase 0x04: return meg_control_r();
\t\t}
\t\treturn 0;
\t}
\toffs_t o = a & 0x3e;
\tswitch(chan_index(a)) {
%(r)s\t}
\treturn 0;
}
"""


def functions(src):
    """Top-level function definitions of swp00.cpp: list of (signature line, full text)."""
    out = []
    lines = src.split("\n")
    i = 0
    while i < len(lines):
        ln = lines[i]
        if re.match(r"^(template<[^>]*> )?[A-Za-z_][\w:<>, ]*[ *&]swp00_device::", ln) and not ln.endswith(";"):
            j = i
            while lines[j] != "}":
                j += 1
            out.append((ln, "\n".join(lines[i:j + 1])))
            i = j + 1
        else:
            i += 1
    return out


def main():
    mame, outdir = Path(sys.argv[1]), Path(sys.argv[2])
    cpp = (mame / "src/devices/sound/swp00.cpp").read_text()
    h = (mame / "src/devices/sound/swp00.h").read_text()

    # class members: MAME's private section, without the device glue
    start = h.index("\tstruct streaming_block {")
    end = h.index("};\n\nDECLARE_DEVICE_TYPE")
    members = h[start:end]
    members = members.replace("\tsound_stream *m_stream;\n\tbool m_require_sync;\n", "")
    members = members.replace("swp00_device", "swp00_ref")
    members = re.sub(r"\tinline auto &rctrl.*?\n\t}\n\n\tinline auto &rchan.*?\n\t}\n\n", "", members, flags=re.S)
    if "address_map" in members or "sound_stream" in members:
        raise SystemExit("swp00.h changed: device glue left in the class members")

    skip = ("swp00_device(", "require_sync", "device_start", "rom_bank_pre_change", "::map(",
            "snd_r", "snd_w")
    body = []
    for sig, text in functions(cpp):
        if any(s in sig for s in skip):
            continue
        if "device_reset" in sig:
            text = text.replace("void swp00_device::device_reset()", "void swp00_ref::reset()")
            text = text.replace("\tm_sample_counter = 0;", "\tm_sample_counter = 0;\n\tm_state_adr = 0;")
        if "sound_stream_update" in sig:
            text = text.replace("void swp00_device::sound_stream_update(sound_stream &stream)",
                                "void swp00_ref::generate(int count, s32 *out)")
            text = text.replace("for(int i=0; i != stream.samples(); i++) {", "for(int i=0; i != count; i++) {")
            for b, n in (("brev", "0x20000"), ("bcho", "0x8000"), ("bvar", "0x20000")):
                text = text.replace("const delay_block %s(" % b, "const delay_block<%s> %s(" % (n, b))
            text = re.sub(r"\t\tstream\.put_int_clamp\(0, i, dry_l >> 6, 0x20000\);\n"
                          r"\t\tstream\.put_int_clamp\(1, i, dry_r >> 6, 0x20000\);\n"
                          r"(\t\tif\(m_musamples\) \{\n.*?\n\t\t\}\n)?",
                          "\t\tout[2*i]   = std::clamp<s32>(dry_l >> 6, -0x20000, 0x1ffff);\n"
                          "\t\tout[2*i+1] = std::clamp<s32>(dry_r >> 6, -0x20000, 0x1ffff);\n", text, flags=re.S)
            text = text.replace("\t\t// Variation block\n",
                                "\t\tif(m_mix_hook) {\n\t\t\tconst s32 mix[7] = { dry_l, dry_r, rev, cho_l, cho_r, var_l, var_r };\n"
                                "\t\t\tm_mix_hook(m_mix_ctx, mix);\n\t\t}\n\n\t\t// Variation block\n", 1)
            if "m_mix_hook" not in text:
                raise SystemExit("sound_stream_update: no '// Variation block' to hook")
            if "stream" in text.replace("streaming", ""):
                raise SystemExit("sound_stream_update: output not replaced")
        text = text.replace("swp00_device", "swp00_ref").replace("m_rom_cache", "m_wave")
        text = text.replace("return read_byte(", "return m_wave.read_byte(")
        text = re.sub(r"\tm_stream->update\(\);[^\n]*\n", "", text)   # also patch 0002's
        text = re.sub(r'\tlogerror\("keyon %02x: %s\\n", chan, m_streaming\[chan\]\.describe\(\)\);\n', "", text)
        body.append(text)

    # channel register decode from map(): rchan(map, 0xNN).rw(FUNC(r), FUNC(w));
    wcases, rcases = [], []
    for idx, r, w in re.findall(r"rchan\(map, (0x[0-9a-f]+)\)\.rw\(FUNC\(swp00_device::(\w+(?:<\d>)?)\), "
                                r"FUNC\(swp00_device::(\w+(?:<\d>)?)\)\);", cpp):
        wcases.append("\tcase %s: %s(o, data); break;\n" % (idx, w))
        rcases.append("\tcase %s: return %s(o);\n" % (idx, r))
    if len(wcases) != 28:
        raise SystemExit("map(): expected 28 channel registers, found %d" % len(wcases))

    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "swp00_ref.h").write_text(HEADER + members + "};\n}\n\n#endif\n")
    src = ["// license:BSD-3-Clause", "// copyright-holders:Olivier Galibert",
           "// MAME's swp00.cpp as a plain C++ class; see swp00_ref.h. Generated by",
           "// cores/mu50/tools/swp00_ref_extract.py; do not edit.",
           '#include "swp00_ref.h"', "", "#include <sstream>", "", "namespace swp00ref {",
           "namespace util { template<typename... T> void stream_format(T &&...) {} }",
           "template<typename... T> static void logerror(T &&...) {}", ""]
    src += body
    src.append(DISPATCH % {"w": "".join(wcases), "r": "".join(rcases)})
    src.append("}")
    (outdir / "swp00_ref.cpp").write_text("\n".join(src) + "\n")
    print("%d functions, %d channel registers" % (len(body), len(wcases)))


if __name__ == "__main__":
    main()
